def _transcript(tmp_path, lignes, nom="sess1"):
    p = tmp_path / ("%s.jsonl" % nom)
    p.write_text("\n".join(json.dumps(x) for x in lignes) + "\n", encoding="utf-8")
    return p


def _base(tmp_path):
    db = tmp_path / "e.db"
    c = sqlite3.connect(db)
    c.execute("CREATE TABLE rag_chunks (id TEXT PRIMARY KEY, source TEXT, text TEXT, domain TEXT, "
              "ingested_at TEXT, created_at TEXT, active INT DEFAULT 1, retraction_status TEXT)")
    c.execute("CREATE INDEX idx_rag_source ON rag_chunks(source)")
    c.execute("CREATE VIRTUAL TABLE rag_fts USING fts5(chunk_id, source, text)")
    c.commit()
    c.close()
    return db


