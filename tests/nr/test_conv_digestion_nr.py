def test_le_point_d_entree_aiguille_le_drapeau_incremental():
    """Chemin REEL du drapeau : lancer __main__ ecrirait les journaux et l'etat REELS du depot -- on verifie donc,
    par l'AST, que `--incremental` mene a index_incremental (et le reste a index_all)."""
    import ast
    src = (ROOT / "app" / "forge_conv_indexer.py").read_text(encoding="utf-8")
    principal = next(n for n in ast.parse(src).body if isinstance(n, ast.If) and "__main__" in ast.unparse(n.test))
    texte = ast.unparse(principal)
    assert "index_incremental() if '--incremental' in sys.argv else index_all()" in texte


