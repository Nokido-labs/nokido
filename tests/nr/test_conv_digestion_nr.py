def _ecrire(f, objs):
    with f.open("a", encoding="utf-8") as fh:
        fh.write("".join(json.dumps(o) + "\n" for o in objs))


def test_incrementale_ne_rend_que_les_tours_fermes(tmp_path):
    import os
    import time
    f = tmp_path / "proj" / "sessinc.jsonl"
    f.parent.mkdir()
    _ecrire(f, [{"type": "user", "message": {"content": "Question une, assez longue pour compter vraiment"}},
                {"type": "assistant", "message": {"content": [{"type": "text",
                                                              "text": "CONCLUSION UNE, prouvee par la mesure du jour."}]}}])
    g1, e = ci.passe_claude(f, None, {})
    assert g1 == [], "un tour encore OUVERT ne doit pas entrer"
    _ecrire(f, [{"type": "user", "message": {"content": "Question deux, elle aussi assez longue pour compter"}}])
    with f.open("a", encoding="utf-8") as fh:
        fh.write('{"type": "assistant", "message": {"conte')         # ligne en cours d'ecriture
    g2, e = ci.passe_claude(f, e, {})
    assert any("CONCLUSION UNE" in t for _s, t, _ts in g2) and len(g2) == 2
    vieux = time.time() - 4000
    os.utime(f, (vieux, vieux))
    g3, e = ci.passe_claude(f, e, {}, maintenant=time.time())
    assert any("Question deux" in t for _s, t, _ts in g3), "le tour d'une session close doit etre solde"
    g4, _e = ci.passe_claude(f, e, {})
    assert g4 == []


def test_la_porte_differe_si_ci_vivante_ou_pression(tmp_path):
    import os
    jobs = tmp_path / "jobs"
    jobs.mkdir()
    (jobs / "job_x.json").write_text(json.dumps({"job_id": "job_x", "script": "tools/ci_local.py", "pid": os.getpid()}))
    assert ci.doit_differer(jobs, mesure=lambda: (40.0, 1.0))[0], "une CI vivante doit differer la passe"
    (jobs / "job_x.rc").write_text("0")
    assert ci.doit_differer(jobs, mesure=lambda: (91.0, 1.0))[0], "une RAM sous pression doit differer"
    assert ci.doit_differer(jobs, mesure=lambda: (40.0, 90.0))[0], "un disque sature doit differer"
    assert not ci.doit_differer(jobs, mesure=lambda: (40.0, 1.0))[0]


