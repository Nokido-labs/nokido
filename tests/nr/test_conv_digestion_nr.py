def test_seule_la_moelle_entre(tmp_path):
    motifs = {}
    frags = list(ci.iter_claude_epure(_transcript(tmp_path, SESSION), motifs))
    textes = " ".join(t for _s, t, _ts in frags)
    assert HUM in textes and "CONCLUSION" in textes
    for bruit in ("def f()", "system-reminder", "longue reflexion", "Je verifie d'abord", "Caveat"):
        assert bruit not in textes, bruit
    assert motifs.get("sortie_outil") == 1 and motifs.get("narration_intermediaire") == 1, motifs
    assert all(s.startswith(ci.PREFIXE_EPURE + "/sess1/") for s, _t, _ts in frags)


def test_l_ancien_schema_de_la_session_est_gele_et_seulement_lui(tmp_path):
    db = _base(tmp_path)
    c = sqlite3.connect(db)
    for s in ("conv_claude/sess1/0", "conv_claude/sess1/1", "conv_claude/sess10/0", "conv_claude/autre/0"):
        c.execute("INSERT INTO rag_chunks (id, source, text, active) VALUES (?,?,?,1)", (s, s, "ancien"))
    c.commit()
    c.close()
    assert ci.geler_ancien("sess1", db) == 2
    c = sqlite3.connect(db)
    etat = {s: (a, m) for s, a, m in c.execute("SELECT source, active, retraction_status FROM rag_chunks")}
    c.close()
    assert etat["conv_claude/sess1/0"] == (0, ci.MOTIF_GEL) and etat["conv_claude/sess1/1"][0] == 0
    assert etat["conv_claude/sess10/0"][0] == 1, "la plage a deborde sur une autre session (sess10)"
    assert etat["conv_claude/autre/0"][0] == 1


def test_deuxieme_passe_idempotente(tmp_path):
    db = _base(tmp_path)
    t = _transcript(tmp_path, SESSION)
    n1 = ci._insert_chunks(list(ci.iter_claude_epure(t, {})), db)
    n2 = ci._insert_chunks(list(ci.iter_claude_epure(t, {})), db)
    assert n1 > 0 and n2 == 0


